-- Private server-only schema. Do not add this schema to Supabase's exposed Data API schemas.
CREATE SCHEMA IF NOT EXISTS veyl;
REVOKE ALL ON SCHEMA veyl FROM PUBLIC;
CREATE TABLE IF NOT EXISTS veyl.schema_migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS veyl.users(id TEXT PRIMARY KEY, handle TEXT UNIQUE NOT NULL, role TEXT NOT NULL CHECK(role IN ('customer','admin')));
CREATE TABLE IF NOT EXISTS veyl.accounts(id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES veyl.users(id), name TEXT NOT NULL, currency TEXT NOT NULL, balance_cents BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS veyl.transactions(id TEXT PRIMARY KEY, account_id TEXT NOT NULL REFERENCES veyl.accounts(id), posted_at TEXT NOT NULL, description TEXT NOT NULL, amount_cents BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS transactions_account ON veyl.transactions(account_id,posted_at);
CREATE TABLE IF NOT EXISTS veyl.sessions(id TEXT PRIMARY KEY, token_hash TEXT UNIQUE NOT NULL, user_id TEXT NOT NULL REFERENCES veyl.users(id), created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_expiry ON veyl.sessions(expires_at);
CREATE TABLE IF NOT EXISTS veyl.signals(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id TEXT NOT NULL, at BIGINT NOT NULL, action TEXT NOT NULL, authorization_outcome TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS signals_session_time ON veyl.signals(session_id,at);
CREATE INDEX IF NOT EXISTS signals_time ON veyl.signals(at);
CREATE TABLE IF NOT EXISTS veyl.events(sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id TEXT, at BIGINT NOT NULL, payload JSONB NOT NULL);
CREATE INDEX IF NOT EXISTS events_time ON veyl.events(at);
CREATE INDEX IF NOT EXISTS events_session ON veyl.events(session_id,sequence);
CREATE TABLE IF NOT EXISTS veyl.settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
